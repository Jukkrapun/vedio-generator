"""Build content/<series>/catalog.md: every episode's topic, tags, lines, status and results.

Usage:
    python tools/catalog.py <series>        # e.g. love-quotes

The catalog is generated from each episode.json + output/<series>/<episode>-<mode>.mp4, so it never
drifts from the real files. Do not edit catalog.md by hand; edit episode.json and re-run.

episode.json fields read (besides title/mode/segments):
    "tags":  ["moving-on", "self-love"]                       topic tags for grouping
    "posts": [{"platform": "tiktok", "date": "2026-11-21",
               "url": "...", "views": 1200, "likes": 80, "saves": 12}]
Status: draft (no render) -> rendered (mp4 exists) -> posted (has posts).
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

from media import ROOT, probe_duration

AUDIO_TAG_RE = re.compile(r"\[[^\]]*\]\s*")
METRICS = ("views", "likes", "saves")


def spoken(text: str | dict) -> str:
    if isinstance(text, dict):  # story mode: {"th": ..., "en": ...}
        text = text.get("th") or next(iter(text.values()), "")
    return AUDIO_TAG_RE.sub("", text).strip()


def load_episode(folder: Path, output_dir: Path) -> dict:
    data = json.loads((folder / "episode.json").read_text(encoding="utf-8"))
    mode = data.get("mode", "image")
    suffix = "story-th" if mode == "story" else mode  # story mode renders one file per language
    video = output_dir / f"{folder.name}-{suffix}.mp4"  # current mode's render
    posts = data.get("posts") or []
    status = "posted" if posts else "rendered" if video.exists() else "draft"
    try:
        duration = f"{probe_duration(video):.1f}s" if video.exists() else "-"
    except Exception as exc:  # broken/partial render shouldn't stop the catalog
        print(f"warning: cannot read duration of {video.name}: {exc}", file=sys.stderr)
        duration = "?"
    totals = {m: sum(int(p.get(m) or 0) for p in posts) for m in METRICS}
    return {
        "name": folder.name,
        "title": data.get("title", ""),
        "mode": data.get("mode", "image"),
        "tags": data.get("tags") or [],
        "lines": [spoken(s["text"]) for s in data.get("segments", []) if not s.get("skip")],
        "status": status,
        "duration": duration,
        "posts": posts,
        "totals": totals,
    }


def fmt_results(ep: dict) -> str:
    if not ep["posts"]:
        return "-"
    t = ep["totals"]
    return f"{t['views']:,} views / {t['likes']:,} likes / {t['saves']:,} saves"


def render(series: str, episodes: list[dict]) -> str:
    out = [
        f"# Catalog: {series}",
        "",
        "Generated by `python tools/catalog.py " + series + "` - do not edit by hand.",
        "Check this before writing a new episode: avoid repeating a topic angle or a line below.",
        "",
        "## Episodes",
        "",
        "| # | Title | Tags | Mode | Status | Length | Results |",
        "|---|---|---|---|---|---|---|",
    ]
    for ep in episodes:
        out.append(f"| {ep['name']} | {ep['title']} | {', '.join(ep['tags']) or '-'} | {ep['mode']} "
                   f"| {ep['status']} | {ep['duration']} | {fmt_results(ep)} |")

    by_tag = defaultdict(list)
    for ep in episodes:
        for tag in ep["tags"] or ["untagged"]:
            by_tag[tag].append(ep["name"][:3])
    out += ["", "## Tags", ""]
    out += [f"- **{tag}** ({len(nums)}): {', '.join(nums)}" for tag, nums in sorted(by_tag.items())]

    posted = sorted((e for e in episodes if e["posts"]), key=lambda e: e["totals"]["views"], reverse=True)
    if posted:
        out += ["", "## Best performing (by views)", ""]
        out += [f"{i}. {e['name']} - {fmt_results(e)}" for i, e in enumerate(posted[:10], 1)]

    out += ["", "## Lines already used", ""]
    for ep in episodes:
        out.append(f"### {ep['name']} - {ep['title']}")
        out += [f"- {line}" for line in ep["lines"]]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def build_catalog(series: str) -> Path:
    series_dir = ROOT / "content" / series
    episodes_dir = series_dir / "episodes"
    if not episodes_dir.is_dir():
        raise FileNotFoundError(f"No episodes folder: {episodes_dir}")
    output_dir = ROOT / "output" / series
    folders = sorted(p for p in episodes_dir.iterdir() if (p / "episode.json").is_file())
    episodes = [load_episode(f, output_dir) for f in folders]
    target = series_dir / "catalog.md"
    target.write_text(render(series, episodes), encoding="utf-8")
    print(f"Catalog updated: {target} ({len(episodes)} episodes)")
    return target


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build_catalog(sys.argv[1])


if __name__ == "__main__":
    main()
